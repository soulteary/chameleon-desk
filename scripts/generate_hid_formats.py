#!/usr/bin/env python3
"""Generate HID layout limits from pinned Python AST; never execute upstream."""
import ast,sys
from pathlib import Path
root=Path(sys.argv[1]);enum=ast.parse((root/'software/script/chameleon_enum.py').read_text());cli=ast.parse((root/'software/script/chameleon_cli_unit.py').read_text())
formats={}
for n in enum.body:
 if isinstance(n,ast.ClassDef) and n.name=='HIDFormat':
  for a in n.body:
   if isinstance(a,ast.Assign) and isinstance(a.value,ast.Constant) and isinstance(a.value.value,int):formats[a.targets[0].id]=a.value.value
limits={}
for n in ast.walk(cli):
 if isinstance(n,ast.ClassDef) and n.name=='LFHIDIdArgsUnit':
  for f in ast.walk(n):
   if isinstance(f,ast.Assign) and any(isinstance(t,ast.Name) and t.id=='limits' for t in f.targets):
    for k,v in zip(f.value.keys,f.value.values):limits[k.attr]=ast.literal_eval(v)
assert formats.keys()==limits.keys()
lines=['// Code generated by scripts/generate_hid_formats.py; DO NOT EDIT.','package chameleon','var hidFormats = map[byte]HIDFormatInfo{']
for name,code in sorted(formats.items(),key=lambda p:p[1]):
 a,b,c,d=limits[name];lines.append(f'{code}:{{ID:{code},Name:"{name}",MaxFacility:{a},MaxNumber:{b},MaxIssue:{c},MaxOEM:{d}}},')
lines.append('}');Path('hid_formats_gen.go').write_text('\n'.join(lines)+'\n')
