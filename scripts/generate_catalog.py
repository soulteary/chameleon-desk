#!/usr/bin/env python3
"""Regenerate from a local pinned upstream checkout; never imports upstream code."""
import ast, json, re, sys, subprocess
from pathlib import Path
up = Path(sys.argv[1])
root = Path(__file__).resolve().parents[1]
sha = subprocess.check_output(['git','-C',str(up),'rev-parse','HEAD'],text=True).strip()
enumfile=up/'software/script/chameleon_enum.py'
module=ast.parse(enumfile.read_text())
commands={}
statuses={}
for node in module.body:
    if isinstance(node,ast.ClassDef) and node.name in ('Command','Status'):
        target=commands if node.name=='Command' else statuses
        for a in node.body:
            if isinstance(a,ast.Assign) and isinstance(a.value,ast.Constant) and isinstance(a.value.value,int):
                target[a.targets[0].id]=a.value.value
header=(up/'firmware/application/src/data_cmd.h').read_text()
for name,num in re.findall(r'#define\s+DATA_CMD_(\w+)\s+\((\d+)\)',header):commands.setdefault(name,int(num))
c=(up/'firmware/application/src/app_cmd.c').read_text()
registered=set(re.findall(r'\{\s*DATA_CMD_(\w+)\s*,',c))
for num,handler in re.findall(r'\{\s*(\d+)\s*,\s*NULL\s*,\s*cmd_processor_(\w+)',c):
    name=handler.upper()
    commands[name]=int(num)
    registered.add(name)

funcs=ast.parse((up/'software/script/chameleon_cmd.py').read_text())
methods={}
for node in ast.walk(funcs):
    if isinstance(node,ast.FunctionDef):
        names=set()
        for v in ast.walk(node):
            if isinstance(v,ast.Attribute) and isinstance(v.value,ast.Name) and v.value.id=='Command':names.add(v.attr)
        for name in names:
            if name in commands:
                methods.setdefault(name,[]).append({'method':node.name,'signature':ast.unparse(node.args),'doc':ast.get_docstring(node) or '', 'source_line':node.lineno,'pack_formats':sorted({v.value for v in ast.walk(node) if isinstance(v,ast.Constant) and isinstance(v.value,str) and re.fullmatch(r'[!><=@][0-9a-zA-Z?]+',v.value)})})
def goname(name):return ''.join(s[0]+s[1:].lower() for s in name.split('_'))
def group(n):return ('device' if n<2000 else 'hf-reader' if n<3000 else 'lf-reader' if n<4000 else 'hf-emulator' if n<5000 else 'lf-emulator' if n<6000 else 'iso14443-4')
def effect(name,n):
    if name=='ENTER_BOOTLOADER':return 'disconnect'
    if name.endswith('DEBUG_COUNTERS'):return 'read'
    if name in ('WIPE_FDS','RESET_SETTINGS'):return 'destructive'
    if name.startswith(('GET_','MF1_GET_','MF0_NTAG_GET_','HF14A_GET_')) or '_GET_' in name or '_READ_EMU_' in name or name=='SEOS_READ_EMU_DATA':return 'read'
    if name.endswith('_SCAN') or name in ('HF14A_SCAN_KEEP','MF1_DETECT_SUPPORT','MF1_DETECT_PRNG','MF1_DETECT_NT_DIST'):return 'rf-read'
    if 'WRITE' in name and ('T55' in name or n<4000):return 'card-write'
    if name in ('HF14A_RAW','HF14A_4_READER_APDU'):return 'rf-raw'
    if name.startswith(('SET_','DELETE_','SAVE_','RESET_','CHANGE_')) or '_SET_' in name or 'WRITE_EMU' in name or name=='SLOT_DATA_CONFIG_SAVE':return 'device-write'
    return 'advanced'
records=[]
for name,num in sorted(commands.items(),key=lambda x:x[1]):
    records.append({'id':num,'name':name,'group':group(num),'effect':effect(name,num),'registered':name in registered,'python':methods.get(name,[]),'firmware_source':'firmware/application/src/app_cmd.c','firmware_line':next((i+1 for i,line in enumerate(c.splitlines()) if re.search(r'\{\s*(?:DATA_CMD_'+re.escape(name)+r'|'+str(num)+r')\s*,',line)),None)})
(root/'internal/catalog').mkdir(parents=True, exist_ok=True)
(root/'internal/catalog/upstream.json').write_text(json.dumps({'commit':sha,'commands':records,'statuses':statuses},indent=2)+'\n')
go=['// Code generated by scripts/generate_catalog.py; DO NOT EDIT.','package chameleon','', 'type Command uint16','const (']
for r in records:go.append(f'Cmd{goname(r["name"])} Command = {r["id"]}')
go+=[')',f'const UpstreamCommit = "{sha}"','var commandCatalog = []CommandInfo{']
for r in records:go.append('{ID:Cmd%s, Name:%s, Group:%s, Effect:%s, Registered:%s},'%(goname(r['name']),json.dumps(r['name']),json.dumps(r['group']),json.dumps(r['effect']),str(r['registered']).lower()))
go+=['}','var statusNames = map[uint16]string{']
for n,v in statuses.items():go.append(f'{v}:{json.dumps(n)},')
go+=['}']
(root/'commands_gen.go').write_text('\n'.join(go)+'\n')
go=['// Code generated by scripts/generate_catalog.py; DO NOT EDIT.','package chameleon','import "context"']
for r in records:
    n=goname(r['name'])
    go.append(f'// Wire{n} sends {r["name"]} with an already encoded payload; it does not change mode automatically.\nfunc(c *Client) Wire{n}(ctx context.Context, payload []byte)(Response,error){{return c.Execute(ctx,Cmd{n},payload)}}')
(root/'wire_gen.go').write_text('\n'.join(go)+'\n')
print(f'{len(records)} catalog commands; {len(registered)} registered; {len(statuses)} statuses; {sha}')
